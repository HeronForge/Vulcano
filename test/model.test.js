test('assignments become quote lines, with the routing and the accessories of an instrument; suggested lines are offered, not added', { skip: !hasWallbox() }, () => {
  const s = open();
  const dmm = s.reqs.find((r) => /multimeter/i.test(r.label));
  const row = s.db.instruments.find((r) => r.classId === 'dmm-6.5');
  row.maker = 'Acme'; row.model = 'DM-6500';
  assert.equal(defaultQty(dmm), 1, 'one instrument by default, however many points: the routing is what the user adds');
  assign(s.job, dmm, { table: 'instruments', itemId: row.id, qty: defaultQty(dmm) });
  const firstLine = linesOf(s.db, dmm, s.job.assignments[dmm.id]);
  assert.equal(firstLine.length, 1, 'no relay line appears by itself');
  assert.deepEqual([firstLine[0].maker, firstLine[0].model], ['Acme', 'DM-6500'], 'the quote line carries the maker and model of the assigned instrument');
  assert.equal(switchingOf(s.job.assignments[dmm.id]), 'dedicated');
  const routing = suggestRouting(s.db, { channels: dmm.channels });
  assert.ok(routing.length >= 3 && routing[0].table === 'parts' && routing[0].row.kind === 'relay', 'relay parts come first');
  const relay = routing.find((x) => x.row.id === 'prt_relay_channel');
  assert.equal(relay.suggestedQty, dmm.channels, 'one relay per point');
  assert.equal(routing.find((x) => x.row.id === 'prt_relay_card_16').suggestedQty, 1, 'one 16-channel card for 10 points');
  addRouting(s.job, dmm.id, { table: 'parts', itemId: 'prt_relay_channel', qty: relay.suggestedQty });
  assert.equal(switchingOf(s.job.assignments[dmm.id]), 'mux', 'a routing makes the instrument switched');
  const accs = accessoriesOf(s.db, s.job.assignments[dmm.id]);
  assert.ok(accs.length >= 2 && accs.every((a) => !a.selected), 'accessories are offered, none ticked');
  setAccessory(s.job, dmm.id, accs[0].name, { selected: true, qty: 2 });
  const lines = linesOf(s.db, dmm, s.job.assignments[dmm.id]);
  assert.equal(lines.length, 3, 'the instrument, its routing, its accessory');
  assert.equal(lines[1].qty, dmm.channels);
  assert.equal(lines[1].part, 'routing');
  assert.equal(lines[1].maker, '', 'a routing relay carries no maker/model — those are for the instrument line');
  assert.equal(lines[2].part, 'accessory');
  assert.equal(lines[2].qty, 2);
  assert.equal(costOf(s.db, dmm, s.job.assignments[dmm.id]), row.price + dmm.channels * 22 + 2 * accs[0].price);
  const probes = s.reqs.find((r) => r.partKind === 'probe' && /1.3/.test(r.label));
  assert.equal(defaultQty(probes), probes.count, 'one contact per point applied on');
  assert.equal(probes.count, probes.subjectIds.length, 'on the showcase every listed point is applied on');
  assign(s.job, probes, { table: 'parts', itemId: 'prt_probe-1.3', qty: defaultQty(probes) });
  const sw = s.reqs.find((r) => r.id === 'sw:steps');
  assign(s.job, sw, { hours: sw.suggestedHours, rateId: 'rat_software' });
  const act = s.reqs.find((r) => r.partKind === 'actuator');
  assign(s.job, act, { none: true, note: 'by the operator' });
  touch(s);
  s.job.quote = { markup: 10, contingency: 5, discount: 0 };
  const q = buildQuote({ db: s.db, job: s.job, reqs: s.reqs, meta: meta(s) });
  assert.equal(q.sections.find((x) => x.id === 'instruments').lines.length, 3);
  assert.equal(q.sections.find((x) => x.id === 'contacts').lines.length, 1, 'an action done by the operator has no line');
  assert.equal(q.hours, sw.suggestedHours);
  assert.ok(Math.abs(q.markup - q.subtotal * 0.1) < 1e-6 && Math.abs(q.contingency - (q.subtotal + q.markup) * 0.05) < 1e-6);
  assert.ok(Math.abs(q.total - (q.subtotal + q.markup + q.contingency)) < 1e-6);
  assert.equal(q.unassigned.length, s.reqs.length - 4);
  assert.equal(progress(s.job, s.reqs).done, 4);
  const sum = projectSummary({ db: s.db, job: s.job, reqs: s.reqs, derived: s.derivedBase, meta: meta(s) });
  assert.equal(sum.progress.done, 4);
  assert.equal(sum.groups.find((g) => g.id === 'instruments').subtotal, costOf(s.db, dmm, s.job.assignments[dmm.id]));
  assert.ok(Math.abs(sum.quote.total - q.total) < 1e-6);
  assert.equal(sum.spec.points, s.derivedBase.points.length);
  const sug = suggestedLines({ db: s.db, job: s.job, reqs: s.reqs, derived: s.derivedBase });
  assert.ok(sug.length >= 8 && sug.every((x) => !x.already));
  assert.equal(s.job.lines.length, 0, 'nothing is added by itself');
  addLine(s.job, { name: sug[0].name, qty: sug[0].qty, unit: sug[0].unit, rateId: sug[0].rateId, price: sug[0].price, section: sug[0].section, patternId: sug[0].patternId, source: 'suggested' });
  assert.equal(suggestedLines({ db: s.db, job: s.job, reqs: s.reqs, derived: s.derivedBase })[0].already, true);
  const q2 = buildQuote({ db: s.db, job: s.job, reqs: s.reqs, meta: meta(s) });
  assert.ok(q2.subtotal > q.subtotal);
  // Another instrument brings its own accessories; the routing is about the points and stays.
  assign(s.job, dmm, { table: 'instruments', itemId: 'ins_daq-mux', qty: 1 });
  assert.equal(s.job.assignments[dmm.id].accessories.length, 0);
  assert.equal(s.job.assignments[dmm.id].routing.length, 1);
  removeRouting(s.job, dmm.id, s.job.assignments[dmm.id].routing[0].id);
  assert.equal(switchingOf(s.job.assignments[dmm.id]), 'dedicated');
  unassign(s.job, dmm.id);
  assert.equal(buildQuote({ db: s.db, job: s.job, reqs: s.reqs, meta: meta(s) }).sections.find((x) => x.id === 'instruments').lines.length, 0);
});

