test('the checklists are a tree and an item becomes a question or a tick', { skip: !hasWallbox() }, () => {
  const s = open();
  s.db.checklists.push({ ...newRow('checklists'), discipline: 'bench', situation: 'Always', title: 'Our own item', why: 'because', when: '' });
  s.db.checklists.push({ ...newRow('checklists'), discipline: 'bench', situation: 'Never here', title: 'Not applicable', why: '', when: 'zebra, giraffe' });
  const t = checklistTree({ records: s.records, kb: s.kb, db: s.db, job: s.job });
  assert.ok(t.tree.length >= 4 && t.tree.every((d) => d.situations.length >= 1));
  assert.ok(t.tree.find((d) => d.discipline === 'bench').situations.some((x) => x.items.some((i) => i.title === 'Our own item')), 'an item with no words always applies');
  assert.ok(!t.tree.flatMap((d) => d.situations).flatMap((x) => x.items).some((i) => i.title === 'Not applicable'), 'an item whose words are absent does not');
  const item = t.tree[0].situations[0].items[0];
  setItem(s.job, item.key, { done: true });
  assert.equal(checklistTree({ records: s.records, kb: s.kb, db: s.db, job: s.job }).done, 1);
  const q = itemToQuestion(s.job, item);
  assert.equal(q.source.kind, 'checklist');
});

test('the database imports and exports table by table and as a whole', () => {
  const db = emptyDb();
  const r1 = importTable(db, 'instruments', EXAMPLE_CATALOGUE);
  assert.equal(r1.added, EXAMPLE_CATALOGUE.instruments.length);
  assert.equal(importTable(db, 'instruments', EXAMPLE_CATALOGUE).replaced, EXAMPLE_CATALOGUE.instruments.length);
  importTable(db, 'parts', EXAMPLE_PARTS);
  importTable(db, 'rates', EXAMPLE_RATE_CARD);
  assert.throws(() => importTable(db, 'rates', EXAMPLE_CATALOGUE), /not a rates file/);
  assert.throws(() => importTable(db, 'items', { format: 'vulcano-items/2', items: [] }), /reads up to vulcano-items\/1/);
  const legacy = importTable(db, 'instruments', { format: 'vulcano-catalogue/1', instruments: [{ id: 'x', name: 'Old shape', characteristics: [{ name: 'DC voltage', value: '0 … 10', unit: 'V' }], accuracy: [{ quantity: 'voltage', percent: 0.1 }], interfaces: ['USB'] }] });
  assert.equal(legacy.added, 1);
  const old = db.instruments.find((r) => r.id === 'x');
  assert.equal(old.characteristics, 'DC voltage 0 … 10 V');
  assert.equal(old.accuracy, 0.1);
  assert.deepEqual(parseCharacteristics('DC voltage 0 … 1000 V; Accuracy ±0.0035 %; Probes 10:1'), [{ name: 'DC voltage', value: '0 … 1000', unit: 'V' }, { name: 'Accuracy', value: '±0.0035', unit: '%' }, { name: 'Probes 10:1', value: '', unit: '' }]);
  const out = exportTable(db, 'instruments', M);
  assert.equal(out.format, 'vulcano-catalogue/1');
  assert.ok(Array.isArray(out.instruments[0].characteristics), 'the export writes characteristics as a list');
  assert.deepEqual(parseAccessories('Test lead set 60; Rack mount kit 110; Something without a price'), [{ name: 'Test lead set', price: 60 }, { name: 'Rack mount kit', price: 110 }, { name: 'Something without a price', price: null }]);
  assert.equal(formatAccessories([{ name: 'Test lead set', price: 60 }, { name: 'Something without a price', price: null }]), 'Test lead set 60; Something without a price');
  assert.equal(formatAccessories(parseAccessories('Rack mount kit 110; Communication interface, GPIB 220')), 'Rack mount kit 110; Communication interface, GPIB 220');
  importTable(db, 'instruments', { format: 'vulcano-catalogue/1', instruments: [{ id: 'y', name: 'With list', accessories: [{ name: 'Cable', price: 12 }], image: 'y.png' }] });
  const y = db.instruments.find((r) => r.id === 'y');
  assert.equal(y.accessories, 'Cable 12');
  assert.equal(y.image, 'y.png');
  assert.deepEqual(exportTable(db, 'instruments', M).instruments.find((r) => r.id === 'y').accessories, [{ name: 'Cable', price: 12 }]);
  const whole = exportDb(db, M);
  const back = importDb(JSON.parse(JSON.stringify(whole)));
  assert.equal(back.instruments.length, db.instruments.length);
  assert.throws(() => importDb({ format: 'vulcano-db/2', db: {} }), /reads up to vulcano-db\/1/);
});

test('a job round-trips through its JSON envelope with the assignments, the questions and the checklist', { skip: !hasWallbox() }, () => {
  const s = open();
  const dmm = s.reqs.find((r) => /multimeter/i.test(r.label));
  assign(s.job, dmm, { table: 'instruments', itemId: s.db.instruments[0].id, qty: 1 });
  addRouting(s.job, dmm.id, { table: 'parts', itemId: 'prt_relay_card_16', qty: 1 });
  setAccessory(s.job, dmm.id, 'Test lead set', { selected: true, qty: 1 });
  fromFinding(s.job.questions, s.findings[0]);
  setItem(s.job, 'CL-BENCH-ESTOP', { done: true });
  const env = jobEnvelope(s.job, { includeAssets: false });
  assert.equal(env.format, 'vulcano-job/1');
  assert.equal(env.job.spec.assetsOmitted, true);
  const s2 = createSession({ db: s.db });
  loadJob(s2, readJobEnvelope(JSON.stringify(env)).job);
  assert.deepEqual(Object.keys(s2.job.assignments), [dmm.id]);
  assert.equal(s2.job.assignments[dmm.id].routing.length, 1);
  assert.deepEqual(s2.job.assignments[dmm.id].accessories, [{ name: 'Test lead set', qty: 1 }]);
  const legacy = readJobEnvelope(JSON.stringify({ ...env, job: { ...env.job, variantId: 'v1', assignments: { [dmm.id]: { table: 'instruments', itemId: s.db.instruments[0].id, qty: 1, topology: 'mux', relayPartId: 'x' } } } })).job;
  const s3 = createSession({ db: s.db });
  loadJob(s3, legacy);
  assert.deepEqual(s3.job.assignments[dmm.id].routing, [], 'a 0.2.0 topology is dropped, not turned into a routing');
  assert.ok(!('variantId' in s3.job) && !('topology' in s3.job.assignments[dmm.id]));
  assert.equal(s2.job.questions.length, 1);
  assert.equal(s2.job.checklist['CL-BENCH-ESTOP'].done, true);
  assert.equal(s2.reqs.length, s.reqs.length);
  assert.throws(() => readJobEnvelope(JSON.stringify({ ...env, format: 'vulcano-job/2' })), /only reads up to vulcano-job\/1/);
  closeJob(s2);
  assert.equal(s2.job, null);
  assert.equal(s2.db.instruments.length, s.db.instruments.length, 'closing the project keeps the database');
});

test('the built file carries empty blocks that the save fills and the boot reads back', { skip: !hasWallbox() }, () => {
  const here = dirname(fileURLToPath(import.meta.url));
  const dist = join(here, '..', 'dist', 'vulcano.html');
  if (!existsSync(dist)) return;
  const html = readFileSync(dist, 'utf8');
  assert.match(html, /<!--VLC:DB--><script type="application\/json" id="vlc-db">null<\/script><!--\/VLC:DB-->/);
  assert.match(html, /<!--VLC:JOB--><script type="application\/json" id="vlc-job">null<\/script><!--\/VLC:JOB-->/);
  // The same replacement file.js applies, on the text instead of the live document.
  const protect = (t) => t.replace(/<\/(script|style)/gi, '<\\/$1').replace(/<!--/g, '\\u003c!--');
  const replace = (h, name, json) => h.replace(new RegExp(`<!--VLC:${name}-->[\\s\\S]*?<!--/VLC:${name}-->`), () => `<!--VLC:${name}--><script type="application/json" id="vlc-${name.toLowerCase()}">${protect(json)}</script><!--/VLC:${name}-->`);
  const s = open();
  s.job.name = 'a name with </script> and <!-- inside';
  const saved = replace(replace(html, 'DB', JSON.stringify(s.db)), 'JOB', JSON.stringify({ ...s.job, spec: { ...s.job.spec, assets: {} } }));
  const read = (name) => JSON.parse(new RegExp(`<script type="application/json" id="vlc-${name}">([\\s\\S]*?)</script>`).exec(saved)[1]);
  assert.equal(read('db').instruments.length, s.db.instruments.length);
  assert.equal(read('job').spec.doc.header.documentCode, 'TS-EVC-0117');
  assert.equal(read('job').name, s.job.name, 'a closing tag or a comment inside the data survives the block');
  assert.equal((saved.match(/<!--VLC:JOB-->/g) || []).length, 1);
});

